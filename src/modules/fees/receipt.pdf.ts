import PDFDocument from 'pdfkit';
import { formatNaira } from '../../common/utils/money';

export interface ReceiptData {
  school: { name: string; address: string | null; phone: string | null; email: string | null };
  receiptNo: string; date: string; studentName: string; admissionNo: string; className: string; termName: string; invoiceNumber: string;
  items: { name: string; amountKobo: number }[]; method: string; reference: string; externalReference: string | null;
  amountKobo: number; feeKobo: number; totalPaidKobo: number; balanceAfterKobo: number | null; receivedBy: string | null; reversed: boolean;
}

const L = 50;
const W = 495;
// The standard PDF fonts have no naira sign, so amounts are written as "NGN".
const money = (kobo: number): string => `NGN ${formatNaira(kobo)}`;

export function renderReceipt(data: ReceiptData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: L, info: { Title: `Receipt ${data.receiptNo}`, Author: data.school.name } });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.font('Helvetica-Bold').fontSize(18).text(data.school.name, L, 50, { width: W, align: 'center' });
    const contact = [data.school.address, data.school.phone, data.school.email].filter(Boolean).join('  |  ');
    if (contact) doc.font('Helvetica').fontSize(9).fillColor('#444444').text(contact, L, 74, { width: W, align: 'center' }).fillColor('black');
    doc.font('Helvetica-Bold').fontSize(14).text('PAYMENT RECEIPT', L, 98, { width: W, align: 'center' });
    if (data.reversed) doc.fillColor('#B00020').fontSize(11).text('THIS PAYMENT WAS REVERSED. THIS RECEIPT IS NO LONGER VALID.', L, 118, { width: W, align: 'center' }).fillColor('black');

    const row = (label: string, value: string, y: number, bold = false): void => {
      doc.font('Helvetica').fontSize(10).fillColor('#444444').text(label, L, y, { width: 150 }).fillColor('black');
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').text(value, L + 150, y, { width: W - 150 });
    };

    let y = 150;
    for (const [label, value] of [
      ['Receipt number', data.receiptNo], ['Date', data.date], ['Student', data.studentName], ['Admission number', data.admissionNo],
      ['Class', data.className], ['Term', data.termName], ['Invoice', data.invoiceNumber], ['Payment method', data.method.toLowerCase()],
      ['Reference', data.reference], ...(data.externalReference ? [['Bank or slip reference', data.externalReference]] : []),
    ] as [string, string][]) {
      row(label, value, y);
      y += 18;
    }

    y += 12;
    doc.moveTo(L, y).lineTo(L + W, y).strokeColor('#BBBBBB').lineWidth(0.5).stroke();
    y += 8;
    doc.font('Helvetica-Bold').fontSize(10).text('Invoice items', L, y);
    y += 16;
    for (const item of data.items) {
      doc.font('Helvetica').fontSize(10).text(item.name, L, y, { width: 330 }).text(money(item.amountKobo), L + 330, y, { width: 165, align: 'right' });
      y += 16;
    }

    y += 10;
    doc.moveTo(L, y).lineTo(L + W, y).stroke();
    y += 10;
    const total = (label: string, kobo: number, bold: boolean): void => {
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(bold ? 12 : 10).text(label, L, y, { width: 330 }).text(money(kobo), L + 330, y, { width: 165, align: 'right' });
      y += bold ? 22 : 18;
    };
    total('Applied to the invoice', data.amountKobo, false);
    if (data.feeKobo > 0) total('Online payment fee', data.feeKobo, false);
    total('Total paid', data.totalPaidKobo, true);
    if (data.balanceAfterKobo !== null) total(data.balanceAfterKobo < 0 ? 'Credit on account after this payment' : 'Balance outstanding after this payment', Math.abs(data.balanceAfterKobo), false);

    if (data.receivedBy) {
      y += 24;
      doc.font('Helvetica').fontSize(9).fillColor('#444444').text(`Received by ${data.receivedBy}`, L, y).fillColor('black');
    }
    doc.font('Helvetica').fontSize(8).fillColor('#666666').text('This receipt was generated by the school system and is valid without a signature.', L, 780, { width: W, align: 'center' });
    doc.end();
  });
}